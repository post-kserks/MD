def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def insert(table, cols, rows):
    out = [f"INSERT INTO {table} ({', '.join(cols)}) VALUES"]
    out.append(",\n".join("    (" + ", ".join(q(v) for v in r) + ")" for r in rows) + ";")
    return "\n".join(out)


def serial(prefix, n=8):
    return prefix + "".join(rnd.choice("ABCDEFGHJKLMNPRSTUVWXYZ0123456789") for _ in range(n))


def add_years(d, years):
    d = date.fromisoformat(d)
    try:
        return d.replace(year=d.year + years).isoformat()
    except ValueError:
        return (d.replace(month=2, day=28, year=d.year + years)).isoformat()


def main():
    manuf = {m[0]: m[1] for m in MODELS}
    dtype = {m[0]: m[3] for m in MODELS}
    used_serials = set()

    def uniq(prefix):
        while True:
            s = serial(prefix)
            if s not in used_serials:
                used_serials.add(s)
                return s

    computers = []
    for inv, model, room, comm, wy, status, wo, host in COMPUTERS:
        warranty = add_years(comm, wy) if wy else None
        computers.append((inv, uniq(manuf[model][:2].upper() + "-"), host, comm, warranty,
                          status, wo, model, room))

    components = []

    def comp(spec, inv):
        ctype, man, mdl, val, unit, has_sn = spec
        components.append((ctype, man, mdl, uniq("S") if has_sn else None, val, unit, inv))

    for inv, model, *_ in COMPUTERS:
        for spec in SPECS[model]:
            spec = REPLACE.get((inv, spec[0]), spec)
            comp(spec, None if (inv, spec[0]) in TO_STOCK else inv)
        for spec in EXTRA.get(inv, []):
            comp(spec, inv)
    for spec in STOCK:
        comp(spec, None)

    owner_dept = {}
    emp_dept = {e[0]: e[8] for e in EMPLOYEES}
    for tab, inv, _iss, ret, _doc in ASSIGNMENTS:
        if ret is None:
            owner_dept[inv] = emp_dept[tab]
    installs = []
    for inv, model, room, comm, wy, status, wo, host in COMPUTERS:
        if status == "списан" or inv in ("ПК-00026", "ПК-00027"):
            continue
        base = date.fromisoformat(comm)
        progs = []
        if dtype[model] == "сервер":
            progs = [12] if model == 9 else [13, 4]
        elif manuf[model] == "Apple":
            progs = [14, 4, 8, 2]
        else:
            progs = [1, 4, 8, 9]
            if status != "в резерве":
                progs.append(2)
        dept = owner_dept.get(inv)
        if dept in (1, 5) and manuf[model] != "Apple":
            progs.append(3)
        if inv in ("ПК-00003", "ПК-00022"):
            progs.append(6)
        if inv in ("ПК-00011", "ПК-00028"):
            progs.append(5)
        if dept == 4 and dtype[model] != "сервер":
            progs.append(11)
        if inv in ("ПК-00005", "ПК-00007", "ПК-00012"):
            progs.append(10)
        for p in progs:
            installs.append((inv, p, (base + timedelta(days=rnd.randint(1, 20))).isoformat()))

    parts = [
        "PRAGMA foreign_keys = ON;",
        "BEGIN TRANSACTION;",
        insert("departments", ["id_department", "name"], DEPARTMENTS),
        insert("rooms", ["id_room", "building", "number", "floor", "room_type"], ROOMS),
        insert("models", ["id_model", "manufacturer", "name", "device_type"], MODELS),
        insert("employees", ["tab_number", "surname", "name", "patronymic", "position", "phone",
                             "email", "dismissal_date", "id_department"], EMPLOYEES),
        insert("computers", ["inv_number", "serial_number", "hostname", "commission_date",
                             "warranty_end", "status", "writeoff_date", "id_model", "id_room"], computers),
        insert("components", ["component_type", "manufacturer", "model", "serial_number",
                              "param_value", "unit", "inv_number"], components),
        insert("programs", ["id_program", "name", "version", "developer", "license_type",
                            "license_count"], PROGRAMS),
        insert("assignments", ["tab_number", "inv_number", "issue_date", "return_date", "doc_number"],
               ASSIGNMENTS),
        insert("software_installs", ["inv_number", "id_program", "install_date"], installs),
        insert("services", ["inv_number", "work_type", "start_date", "end_date", "fault_description",
                            "works_done", "cost", "executor_tab_number", "service_org"], SERVICES),
        "COMMIT;",
        "",
    ]
    OUT.write_text("\n\n".join(parts), encoding="utf-8")
    print(OUT, f"компьютеров: {len(computers)}, комплектующих: {len(components)}, "
               f"установок ПО: {len(installs)}")


if __name__ == "__main__":
    main()
